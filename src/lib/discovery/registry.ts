export function getRegisteredSources(): SourceRegistryItem[] {
  return [...SOURCE_REGISTRY];
}

export function getSourceById(id: string): SourceRegistryItem | undefined {
  return SOURCE_REGISTRY.find((s) => s.id === id);
}

export function getActiveProviders(): SourceRegistryItem[] {
  return SOURCE_REGISTRY.filter((s) => s.enabled);
}
